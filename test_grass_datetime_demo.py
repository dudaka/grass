def print_separator(title):
    """Print a formatted separator for test sections."""
    print(f"\n{'=' * 60}")
    print(f" {title}")
    print('=' * 60)


def print_datetime_info(dt, name="DateTime"):
    """Print detailed information about a DateTime structure."""
    print(f"{name}:")
    print(f"  Mode: {dt.mode}")
    print(f"  From: {getattr(dt, 'from')}")  # 'from' is a Python keyword
    print(f"  To: {dt.to}")
    print(f"  Year: {dt.year}")
    print(f"  Month: {dt.month}")
    print(f"  Day: {dt.day}")
    print(f"  Hour: {dt.hour}")
    print(f"  Minute: {dt.minute}")
    print(f"  Second: {dt.second}")
    print(f"  Positive: {dt.positive}")
    print(f"  Timezone: {dt.tz}")
    print(f"  Fracsec: {dt.fracsec}")


def check_error():
    """Check for GRASS datetime errors and print them."""
    if datetime_error_code() != 0:
        error_msg = datetime_error_msg()
        print(f"  ⚠️  GRASS Error {datetime_error_code()}: {error_msg}")
        datetime_clear_error()
        return True
    return False



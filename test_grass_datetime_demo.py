def test_datetime_scanning():
    """Test parsing datetime strings."""
    print_separator("Testing DateTime String Parsing")
    
    test_strings = [
        "2025-09-04 14:30:45",
        "2025-09-04",
        "14:30:45",
        "2025",
        "invalid-date"
    ]
    
    for date_str in test_strings:
        dt = DateTime()
        print(f"\nTesting string: '{date_str}'")
        
        result = datetime_scan(byref(dt), date_str.encode('utf-8'))
        print(f"  Parse result: {result}")
        
        if not check_error() and result == 0:
            print("  ✓ Successfully parsed")
            print_datetime_info(dt, "  Parsed DateTime")
        else:
            print("  ✗ Failed to parse")


